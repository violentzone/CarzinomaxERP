def _attendance_detail(a: AttendanceLog) -> UserAttendanceDetail:
    """
    Converts an attendance log row to its output model, deriving hours from the clock times when `total_hours` is not stored
    Args:
        a: Attendance log row

    Returns:
        Attendance detail with `hours` of 0.0 when the row has no clock-out
    """
    if a.total_hours is not None:
        hours = float(a.total_hours)
    elif a.clock_out is not None:
        hours = (a.clock_out - a.clock_in).total_seconds() / 3600
    else:
        hours = 0.0
    return UserAttendanceDetail(
        id=a.id,
        user_id=a.user_id,
        date=a.date,
        clocked_in=a.clock_in,
        clocked_out=a.clock_out,
        hours=hours,
    )

@tool
def get_attendance(
    start_date: date_type,
    end_date: date_type,
    user_id: int | None = None,
    include_open: bool = False,
) -> GetAttendanceOutput | None:
    """
    Gets attendance logs from database table "attendance_logs" in provided duration, filtered by parameters that is not None
    Args:
        start_date: Start period to query attendance (inclusive, by date)
        end_date: End period to query attendance (inclusive, by date)
        user_id: User ID whose logs to query, None if query all users
        include_open: True to also return logs without a clock-out (still clocked in, hours 0.0), False to return completed logs only

    Returns:
        Attendance logs in provided duration, each user/day data listed in `GetAttendanceOutput.user_detail` with summed hours in `total_hours`, None if no log fits condition
    """
    stmt = select(AttendanceLog)
    stmt = stmt.where(AttendanceLog.date >= start_date)
    stmt = stmt.where(AttendanceLog.date <= end_date)
    if user_id is not None:
        stmt = stmt.where(AttendanceLog.user_id == user_id)
    if not include_open:
        stmt = stmt.where(AttendanceLog.clock_out.is_not(None))

    with SyncSessionLocal() as session:
        logs = (session.execute(stmt)).scalars().all()

    if not logs:
        return None
    user_detail = [_attendance_detail(a) for a in logs]
    return GetAttendanceOutput(
        user_detail=user_detail,
        total_hours=sum(d.hours for d in user_detail),
    )

@tool
def create_attendance(
    user_id: int,
    date: date_type,
    clock_in: datetime,
    clock_out: datetime | None = None,
) -> UserAttendanceDetail:
    """
    Creates a new attendance log into database table "attendance_logs", total hours are computed when both clock times are given
    Args:
        user_id: ID of the user who clocks in, must exist
        date: Working date of the log
        clock_in: Clock-in time
        clock_out: Clock-out time, None if the user is still clocked in

    Returns:
        The created attendance log record
    """
    if clock_out is not None and clock_out < clock_in:
        raise ValueError('Clock-out time must not be earlier than clock-in time')

    with SyncSessionLocal() as session:
        if session.get(User, user_id) is None:
            raise ValueError(f'User with id {user_id} not found')

        attendance = AttendanceLog(
            user_id=user_id,
            date=date,
            clock_in=clock_in,
            clock_out=clock_out,
            total_hours=(clock_out - clock_in).total_seconds() / 3600 if clock_out is not None else None,
        )
        session.add(attendance)
        session.commit()
        session.refresh(attendance)

    return _attendance_detail(attendance)

@tool
def update_attendance(
    attendance_id: int,
    clock_in: datetime | None = None,
    clock_out: datetime | None = None,
    total_hours: float | None = None,
) -> UserAttendanceDetail:
    """
    Updates an existing attendance log in database table "attendance_logs", only fields that is not None are changed; total hours are recomputed from the clock times when a clock time changes and `total_hours` is not given
    Args:
        attendance_id: ID of the attendance log to update
        clock_in: New clock-in time, None if not change
        clock_out: New clock-out time (use this to clock a user out), None if not change
        total_hours: Explicit total hours to store, None to compute from the clock times

    Returns:
        The updated attendance log record
    """
    with SyncSessionLocal() as session:
        attendance = session.get(AttendanceLog, attendance_id)
        if attendance is None:
            raise ValueError(f'Attendance log with id {attendance_id} not found')
        if clock_in is not None:
            attendance.clock_in = clock_in
        if clock_out is not None:
            attendance.clock_out = clock_out
        if attendance.clock_out is not None and attendance.clock_out < attendance.clock_in:
            raise ValueError('Clock-out time must not be earlier than clock-in time')
        if total_hours is not None:
            attendance.total_hours = total_hours
        elif (clock_in is not None or clock_out is not None) and attendance.clock_out is not None:
            attendance.total_hours = (attendance.clock_out - attendance.clock_in).total_seconds() / 3600
        session.commit()
        session.refresh(attendance)

    return _attendance_detail(attendance)

