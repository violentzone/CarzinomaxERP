class UserInfo(BaseModel):
    id: int | None = None
    full_name: str | None = None
    email: str | None = None
    is_active: bool | None = None
    has_finance_access: bool | None = None
    has_scm_access: bool | None = None
    has_hr_access: bool | None = None
    has_dev_access: bool | None = None

class GetUserOutput(BaseModel):
    user_detail: list[UserInfo]
    total: int


@tool
def get_user_info(
    target_user_id: int | None = None,
    target_user_name: str | None = None,
    has_finance_access: bool | None = None,
    has_scm_access: bool | None = None,
    has_hr_access: bool | None = None,
    has_dev_access: bool | None = None,
) -> GetUserOutput | None:
    """
    Gets user information from database table "users", filtered by parameters that is not None
    Args:
        target_user_id: Target user ID to query, None if not filter by ID
        target_user_name: Target user full name (exact match), None if not filter by name
        has_finance_access: Filter user with finance access, None if do not want to filter by finance access
        has_scm_access: Filter user with SCM access, None if do not want to filter by SCM access
        has_hr_access: Filter user with HR access, None if do not want to filter by HR access
        has_dev_access: Filter user with dev access, None if do not want to filter by dev access

    Returns:
        Every user that fits the condition listed in `GetUserOutput.user_detail` with count in `total`, all users if no filter given, None if no user fits
    """
    stmt = select(User)
    if target_user_id is not None:
        stmt = stmt.where(User.id == target_user_id)
    if target_user_name is not None:
        stmt = stmt.where(User.full_name == target_user_name)
    if has_finance_access is not None:
        stmt = stmt.where(User.has_finance_access == has_finance_access)
    if has_scm_access is not None:
        stmt = stmt.where(User.has_scm_access == has_scm_access)
    if has_hr_access is not None:
        stmt = stmt.where(User.has_hr_access == has_hr_access)
    if has_dev_access is not None:
        stmt = stmt.where(User.has_dev_access == has_dev_access)

    with SyncSessionLocal() as session:
        users = (session.execute(stmt)).scalars().all()

    if not users:
        return None
    return GetUserOutput(
        user_detail=[UserInfo.model_validate(u, from_attributes=True) for u in users],
        total=len(users),
    )

@tool
def create_user(
    new_user_email: str,
    password: str,
    full_name: str | None = None,
    is_active: bool = True,
    has_finance_access: bool = False,
    has_scm_access: bool = False,
    has_hr_access: bool = False,
    has_dev_access: bool = False,
) -> UserInfo:
    """
    Creates a new user into database table "users", user ID is generated by default, password will be hashed and original password will not be saved, permissions default to False if not given
    Args:
        new_user_email: User email to create, this value will be the account when login, must not already exist
        password: Plain text password of user, will be hashed before saving
        full_name: Full name of user, None if not given
        is_active: Whether the user can log in, defaults to True
        has_finance_access: Permission of newly created user with finance access
        has_scm_access: Permission of newly created user with SCM access
        has_hr_access: Permission of newly created user with HR access
        has_dev_access: Permission of newly created user with dev access

    Returns:
        The created user record
    """
    with SyncSessionLocal() as session:
        existing_user = session.execute(select(User).where(User.email == new_user_email)).scalar_one_or_none()
        if existing_user is not None:
            raise ValueError(f'User with email {new_user_email} already exists')

        user = User(
            email=new_user_email,
            hashed_password=get_password_hash(password),
            full_name=full_name,
            is_active=is_active,
            has_finance_access=has_finance_access,
            has_scm_access=has_scm_access,
            has_hr_access=has_hr_access,
            has_dev_access=has_dev_access,
        )
        session.add(user)
        session.commit()
        session.refresh(user)

    return UserInfo.model_validate(user, from_attributes=True)

@tool
def update_user(
    target_user_id: int,
    full_name: str | None = None,
    email: str | None = None,
    password: str | None = None,
    is_active: bool | None = None,
    has_finance_access: bool | None = None,
    has_scm_access: bool | None = None,
    has_hr_access: bool | None = None,
    has_dev_access: bool | None = None,
) -> UserInfo:
    """
    Updates an existing user in database table "users", only fields that is not None are changed
    Args:
        target_user_id: ID of the user to update
        full_name: New full name, None if not change
        email: New login email, must not be used by another user, None if not change
        password: New plain text password, will be hashed before saving, None if not change
        is_active: Whether the user can log in, None if not change
        has_finance_access: New finance access permission, None if not change
        has_scm_access: New SCM access permission, None if not change
        has_hr_access: New HR access permission, None if not change
        has_dev_access: New dev access permission, None if not change

    Returns:
        The updated user record
    """
    with SyncSessionLocal() as session:
        user = session.get(User, target_user_id)
        if user is None:
            raise ValueError(f'User with id {target_user_id} not found')
        if email is not None and email != user.email:
            existing_user = session.execute(select(User).where(User.email == email)).scalar_one_or_none()
            if existing_user is not None:
                raise ValueError(f'User with email {email} already exists')
            user.email = email
        if full_name is not None:
            user.full_name = full_name
        if password is not None:
            user.hashed_password = get_password_hash(password)
        if is_active is not None:
            user.is_active = is_active
        if has_finance_access is not None:
            user.has_finance_access = has_finance_access
        if has_scm_access is not None:
            user.has_scm_access = has_scm_access
        if has_hr_access is not None:
            user.has_hr_access = has_hr_access
        if has_dev_access is not None:
            user.has_dev_access = has_dev_access
        session.commit()
        session.refresh(user)

    return UserInfo.model_validate(user, from_attributes=True)

